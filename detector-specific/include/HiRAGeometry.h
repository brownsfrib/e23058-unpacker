#ifndef HIRAGEOMETRY_H
#define HIRAGEOMETRY_H

// C/C++ includes
#include <cstdint>
#include <string>
#include <unordered_map>
#include <vector>

// Unpacker includes
#include "Config.h"
#include "HiRA.h"
#include "HiRAData.h"

// One silicon strip (from the strip .dat made by toBinary_HIRA)
struct HiRAChannel {
	int         motherboard = 0, chip = 0, strip = 0;	// electronics address, strip 0-31
	int         telescope   = 0;
	int         face        = 0;				// 0 = front (EF), 1 = back (EB)
	int         csi[2]      = {-1, -1};			// the two CsI behind the strip (global 4*P + q)
	std::string detCode;
	double      theta = 0, thetaMin = 0, thetaMax = 0, dtheta = 0;	// dtheta = half-width
	double      phi   = 0, phiMin   = 0, phiMax   = 0, dphi   = 0;
};

// One CsI crystal (HiRA_csi.csv)
struct HiRACsI {
	bool   valid = false;
	int    id = -1, telescope = -1, quadrant = -1;		// id = 4*telescope + quadrant
	int    adcModule = -1, adcChannel = -1, tdcChannel = -1;
	double theta = 0, thetaMin = 0, thetaMax = 0, dtheta = 0;
	double phi   = 0, phiMin   = 0, phiMax   = 0, dphi   = 0;
};

// One pixel = front strip x back strip (HiRA_pixels.csv)
struct HiRAPixel {
	bool   valid = false;
	int    csi   = -1;					// global CsI behind the pixel
	double theta = 0, dtheta = 0, phi = 0, dphi = 0;	// dtheta/dphi = half-widths
};

/**
 * !\brief HiRA geometry: electronics -> telescope/strip/CsI mapping and angles.
 *
 * HiRAConfig.dat [geometry]:
 *   STRIP_TABLE  <.dat from toBinary_HIRA>   (motherboard, chip, strip) -> telescope, face, angles
 *   CSI_TABLE    <HiRA_csi.csv>              CsI -> ADC/TDC channel, angles
 *   PIXEL_TABLE  <HiRA_pixels.csv>           (telescope, EF, EB) -> CsI, angles
 * All three are generated by input/HIRA/geometry/build_hira_geometry.py.
 */
class HiRAGeometry{
	public:
		static const int kNCsI = 48, kNTele = 12, kNStrips = 32;

		bool Load(const Config &cfg);

		// fill HIRA strip and CsI blocks from the decoded readout (clears data first)
		void Map(const HiRA &reader, HiRAData &data);

		const HiRAChannel *Get(int motherboard, int chip, int strip) const;	// nullptr if unknown
		const HiRACsI     *GetCsI(int id) const;
		const HiRAPixel   *GetPixel(int telescope, int ef, int eb) const;

		void PrintSummary() const;

	private:
		bool LoadStrips(const std::string &path);
		bool LoadCsI(const std::string &path);
		bool LoadPixels(const std::string &path);

		static uint32_t Key(int mb, int chip, int strip){
			return ((uint32_t)(mb & 0xff) << 16) | ((uint32_t)(chip & 0xff) << 8) | (uint32_t)(strip & 0xff);
		}
		std::unordered_map<uint32_t, HiRAChannel> fStrips;
		std::vector<HiRACsI>   fCsI;
		std::vector<HiRAPixel> fPix;

		long fUnmapped = 0;		// strips not in the strip table
};

#endif // HIRAGEOMETRY_H
