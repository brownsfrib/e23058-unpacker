#ifndef HIRAGEOMETRY_H
#define HIRAGEOMETRY_H

// C/C++ includes
#include <cstdint>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>
#include <unordered_map>
#include <vector>

// One silicon strip: which detector/telescope/CsI it belongs to and where it points
struct HiRAChannel {
	int         motherboard = 0;
	int         chip        = 0;
	int         strip       = 0;	// board strip, 0-31
	int         telescope   = 0;	// P0-P11
	int         face        = 0;	// 0 = front (EF, vertical strips), 1 = back (EB)
	int         csi[2]      = {-1, -1};	// the two CsI behind this strip (global 4*P + quadrant)
	std::string detCode;		// silicon detector code, e.g. "2344-11"
	double      theta = 0.0, thetaMin = 0.0, thetaMax = 0.0, dtheta = 0.0;
	double      phi   = 0.0, phiMin   = 0.0, phiMax   = 0.0, dphi   = 0.0;
};

// One CsI crystal (from HiRA_csi.csv)
struct HiRACsI {
	bool   valid      = false;
	int    id         = -1;	// global 4*telescope + quadrant
	int    telescope  = -1;
	int    quadrant   = -1;	// 0 top-left, 1 bottom-left, 2 bottom-right, 3 top-right
	int    adcModule  = -1;	// -1 = not mapped
	int    adcChannel = -1;
	int    tdcChannel = -1;
	double theta = 0.0, thetaMin = 0.0, thetaMax = 0.0, dtheta = 0.0;
	double phi   = 0.0, phiMin   = 0.0, phiMax   = 0.0, dphi   = 0.0;
};

// One pixel (front strip x back strip) of one telescope (from HiRA_pixels.csv)
struct HiRAPixel {
	bool   valid  = false;
	int    csi    = -1;	// global CsI behind this pixel (4*telescope + quadrant)
	double theta  = 0.0, dtheta = 0.0;
	double phi    = 0.0, dphi   = 0.0;
};

/**
 * !\brief HiRA geometry lookups, all generated by build_hira_geometry.py.
 *
 *   Load(".dat")       strips: (motherboard, chip, strip) -> HiRAChannel
 *                      record (108 bytes, written by write_hira_channels):
 *                        int32 motherboard, chip; char detCode[16];
 *                        int32 strip, telescope, face, csiA, csiB;
 *                        double theta, thetaMin, thetaMax, dtheta,
 *                               phi,   phiMin,   phiMax,   dphi
 *   LoadCsI(".csv")    CsI: global id -> HiRACsI (reads HiRA_csi.csv directly)
 *   LoadPixels(".csv") pixels: (telescope, ef, eb) -> HiRAPixel (reads HiRA_pixels.csv)
 *
 * Angles in degrees. Strip ranges are wide along the strip (a front strip spans
 * the full detector height); use the pixel (front x back strip) for hit angles.
 */
class HiRAGeometry{
	public:
		static const int kCodeLen = 16;
		static const int kNCsI    = 48;
		static const int kNTele   = 12;
		static const int kNStrips = 32;

		bool Load(const std::string &path){
			std::ifstream fin(path.c_str(), std::ios::binary);
			if (!fin){
				std::cerr << "\033[1;31mHiRAGeometry: cannot open " << path << "\033[0m\n";
				return false;
			}
			int32_t ints1[2], ints2[5];
			char    code[kCodeLen];
			double  ang[8];
			fTable.clear();
			while (fin.read((char*)ints1, sizeof ints1) &&
			       fin.read(code,         kCodeLen)     &&
			       fin.read((char*)ints2, sizeof ints2) &&
			       fin.read((char*)ang,   sizeof ang)){
				HiRAChannel c;
				c.motherboard = ints1[0];
				c.chip        = ints1[1];
				c.detCode     = std::string(code, strnlen(code, kCodeLen));
				c.strip       = ints2[0];
				c.telescope   = ints2[1];
				c.face        = ints2[2];
				c.csi[0]      = ints2[3];
				c.csi[1]      = ints2[4];
				c.theta = ang[0];  c.thetaMin = ang[1];  c.thetaMax = ang[2];  c.dtheta = ang[3];
				c.phi   = ang[4];  c.phiMin   = ang[5];  c.phiMax   = ang[6];  c.dphi   = ang[7];
				fTable[Key(c.motherboard, c.chip, c.strip)] = c;
			}
			std::cout << "HiRAGeometry: loaded " << fTable.size() << " strips from " << path << "\n";
			return !fTable.empty();
		}

		// HiRA_csi.csv: csi,telescope,quadrant,adc_module,adc_channel,tdc_channel,
		//               theta,theta_min,theta_max,dtheta,phi,phi_min,phi_max,dphi
		bool LoadCsI(const std::string &path){
			std::ifstream fin(path.c_str());
			if (!fin){
				std::cerr << "\033[1;31mHiRAGeometry: cannot open " << path << "\033[0m\n";
				return false;
			}
			fCsI.assign(kNCsI, HiRACsI());
			std::string line;
			int n = 0;
			while (std::getline(fin, line)){
				if (line.empty() || line[0] < '0' || line[0] > '9'){
					continue;		// header / comments
				}
				std::vector<double> v;
				std::stringstream ss(line);
				std::string field;
				while (std::getline(ss, field, ',')){
					v.push_back(std::atof(field.c_str()));
				}
				if (v.size() < 14 || v[0] < 0 || v[0] >= kNCsI){
					continue;
				}
				HiRACsI &c = fCsI[(int)v[0]];
				c.valid = true;
				c.id = (int)v[0];         c.telescope  = (int)v[1];  c.quadrant   = (int)v[2];
				c.adcModule = (int)v[3];  c.adcChannel = (int)v[4];  c.tdcChannel = (int)v[5];
				c.theta = v[6];   c.thetaMin = v[7];   c.thetaMax = v[8];   c.dtheta = v[9];
				c.phi   = v[10];  c.phiMin   = v[11];  c.phiMax   = v[12];  c.dphi   = v[13];
				n++;
			}
			std::cout << "HiRAGeometry: loaded " << n << " CsI from " << path << "\n";
			return n > 0;
		}

		// HiRA_pixels.csv: telescope,ef,eb,csi,theta,dtheta,phi,dphi
		bool LoadPixels(const std::string &path){
			std::ifstream fin(path.c_str());
			if (!fin){
				std::cerr << "\033[1;31mHiRAGeometry: cannot open " << path << "\033[0m\n";
				return false;
			}
			fPix.assign(kNTele * kNStrips * kNStrips, HiRAPixel());
			std::string line;
			int n = 0;
			while (std::getline(fin, line)){
				if (line.empty() || line[0] < '0' || line[0] > '9'){
					continue;		// header / comments
				}
				std::vector<double> v;
				std::stringstream ss(line);
				std::string field;
				while (std::getline(ss, field, ',')){
					v.push_back(std::atof(field.c_str()));
				}
				if (v.size() < 8){
					continue;
				}
				int t = (int)v[0], ef = (int)v[1], eb = (int)v[2];
				if (t < 0 || t >= kNTele || ef < 0 || ef >= kNStrips || eb < 0 || eb >= kNStrips){
					continue;
				}
				HiRAPixel &p = fPix[(t * kNStrips + ef) * kNStrips + eb];
				p.valid = true;
				p.csi   = (int)v[3];
				p.theta = v[4];  p.dtheta = v[5];
				p.phi   = v[6];  p.dphi   = v[7];
				n++;
			}
			std::cout << "HiRAGeometry: loaded " << n << " pixels from " << path << "\n";
			return n > 0;
		}

		// nullptr if out of range or not loaded
		const HiRAPixel *GetPixel(int telescope, int ef, int eb) const{
			if (telescope < 0 || telescope >= kNTele || ef < 0 || ef >= kNStrips || eb < 0 || eb >= kNStrips
			    || fPix.empty()){
				return nullptr;
			}
			const HiRAPixel &p = fPix[(telescope * kNStrips + ef) * kNStrips + eb];
			return p.valid ? &p : nullptr;
		}

		// nullptr if the strip is not in the file
		const HiRAChannel *Get(int motherboard, int chip, int strip) const{
			std::unordered_map<uint32_t, HiRAChannel>::const_iterator it =
				fTable.find(Key(motherboard, chip, strip));
			return (it == fTable.end()) ? nullptr : &it->second;
		}

		// nullptr if the CsI id is out of range or not loaded
		const HiRACsI *GetCsI(int id) const{
			if (id < 0 || id >= (int)fCsI.size() || !fCsI[id].valid){
				return nullptr;
			}
			return &fCsI[id];
		}

		int Size()    const { return (int)fTable.size(); }
		int SizeCsI() const { int n = 0; for (size_t i = 0; i < fCsI.size(); i++) n += fCsI[i].valid; return n; }

	private:
		static uint32_t Key(int mb, int chip, int strip){
			return ((uint32_t)(mb & 0xff) << 16) | ((uint32_t)(chip & 0xff) << 8) | (uint32_t)(strip & 0xff);
		}
		std::unordered_map<uint32_t, HiRAChannel> fTable;
		std::vector<HiRACsI> fCsI;
		std::vector<HiRAPixel> fPix;
};

#endif // HIRAGEOMETRY_H
